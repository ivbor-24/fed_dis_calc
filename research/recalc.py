"""Пересчёт примеров ROI из материалов по модулям nanoCAD.

Допущения берутся из калькулятора (index.html) и исходных docx:
 - ЗП ОКВЭД 71 (ЕМИСС, янв-апр 2026) 146 000 руб./мес, 21 раб. день;
 - соцотчисления 13.92/40.06 от ФОТ (707/пр, табл. 1.1);
 - доля ФОТ+соц. в себестоимости 53.98%, рентабельность 10%;
 - 10 проектов в год, 8 ч в дне.
Для каждого примера печатается: как в документе -> как получается при
последовательном применении той же логики.
"""

ZP, DAYS, SOC = 146_000, 21, 13.92 / 40.06
DAY = ZP / DAYS * (1 + SOC)          # ≈ 9 369 руб./чел-день
HOUR = DAY / 8                       # ≈ 1 171 руб./ч
N = 10

def md(section_price):
    """Цена раздела (без НДС) -> чел-дни на ФОТ."""
    return section_price / 1.1 * 0.5398 / DAY

def roi(name, work_days, saved_days, reserve_days, reserve_cut, cost, doc):
    fot = saved_days * DAY * N
    loss = reserve_days * reserve_cut * DAY * N
    net = fot + loss - cost
    per_project = saved_days * DAY + reserve_days * reserve_cut * DAY
    load = (work_days + reserve_days) * N
    print(f"\n{name}")
    print(f"  в документе: ФОТ {doc[0]:>10,.0f}  L {doc[1]:>9,.0f}  ROI {doc[2]:>5}%")
    print(f"  пересчёт:    ФОТ {fot:>10,.0f}  L {loss:>9,.0f}  ROI {net / cost * 100:>5.0f}%"
          f"  | эффект {net:,.0f}; окупаемость {cost / per_project:.1f} проекта")
    print(f"  загрузка: {load:.0f} чел-дней/год при 10 проектах "
          f"(≈{load / 247:.1f} ставки при 247 раб. днях)")

print(f"Ставка: {DAY:,.0f} руб./чел-день, {HOUR:,.0f} руб./ч")
print(f"Детсад ПБ+СС+АВТ 10.5% от 9.923 млн -> {md(1_041_900):.1f} чел-дн")
print(f"Детсад ЭО 4.7% -> {md(467_000):.1f} чел-дн")
print(f"Котельная ЭО 10.3% от 9.3 млн = {0.103 * 9.3e6:,.0f} -> {md(0.103 * 9.3e6):.1f} чел-дн")
print(f"Котельная СС+ПБ (без АВТ) 1.8% = {0.018 * 9.3e6:,.0f} -> {md(0.018 * 9.3e6):.1f} чел-дн")

OPS_SKS = 59_800 + 62_900 + 25_400 + 2 * 16_700   # ОПС 59 800, не 62 900
ELEKTRO = 71_500 + 25_400 + 25_100
SPDS = 69_900 + 30_000

roi("ОПС+СКС / детсад", 43, 9, 12, 0.5, OPS_SKS, (843_100, 280_100, 508))
roi("ОПС+СКС / котельная (как в док., с АВТ)", 50, 12, 12, 0.5, OPS_SKS, (1_124_400, 281_000, 661))
roi("Электро / детсад", 20, 6, 5, 0.5, ELEKTRO, (562_000, 117_000, 457))
roi("Электро / котельная", 40, 10, 10, 0.5, ELEKTRO, (936_800, 234_000, 860))
roi("СПДС / детсад", 46, 10, 6, 0.5, SPDS, (937_000, 140_500, 978))
roi("СПДС / котельная", 44, 13, 5, 0.5, SPDS, (1_217_800, 234_000, 1353))

# Вариант «на одно рабочее место»: сколько проектов реально успевает один
# инженер за год (247 раб. дней) при сохранённой загрузке, и ROI одной лицензии.
# Консервативно: сокращение резерва на согласования 25% (как фактически
# получилось в документах из-за двойного ×50%).
print("\nНа одно рабочее место, резерв −25%:")
for name, work, saved, reserve, cost in [
    ("ОПС+СКС / детсад", 43, 9, 12, OPS_SKS),
    ("Электро / детсад", 20, 6, 5, ELEKTRO),
    ("Электро / котельная", 40, 10, 10, ELEKTRO),
    ("СПДС / детсад", 46, 10, 6, SPDS),
]:
    n = 247 / (work + reserve)
    gain = (saved + reserve * 0.25) * DAY * n
    print(f"  {name:22} {n:4.1f} проекта/год  эффект {gain - cost:>9,.0f}  ROI {(gain - cost) / cost * 100:4.0f}%")
